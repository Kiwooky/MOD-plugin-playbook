#!/usr/bin/env python3
"""Write ALL-IN-ONE.md: everything a chat-only AI needs, in one file to attach.

    python3 tools/make_all_in_one.py [--cookbook <mod-plugin-cookbook checkout>]

Some chat apps can't fetch GitHub files (GitHub blocks /tree/ and /raw/ for bots,
and some apps refuse raw.githubusercontent.com or URLs not given by the user).
ALL-IN-ONE.md is the fallback: AGENTS.md, the cookbook's recipe prompt (which
includes its worked gain.mk), the docs a single-.mk build needs, and the template
plugin. Re-run it whenever those change; the release checklist does.
Without --cookbook, the cookbook prompt is fetched from GitHub.

It also refreshes two things agents read instead of fetching other sites:
  cookbook/        copies of MOD's cookbook prompt and examples (MIT), so agents
                   read them from this repo (some chat apps can't fetch MOD's repo)
  examples/simple-echo.mk   the template assembled into a single-file recipe:
                   the shape to copy, with the playbook's overrides already applied
If the network is down, the existing cookbook/ copies are used.
"""
import argparse, datetime, os, shutil, subprocess, sys, tempfile, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COOKBOOK_RAW = 'https://raw.githubusercontent.com/mod-audio/mod-plugin-cookbook/main/'
DOCS = ['docs/effect-profile.md', 'docs/path-a-single-recipe.md', 'docs/lv2-and-mod-rules.md',
        'docs/dsp.md', 'docs/dsp-time.md', 'docs/dsp-reverb.md', 'docs/dsp-drive.md',
        'docs/dsp-envelope.md', 'docs/dsp-pitch.md', 'docs/hardware-feedback.md', 'docs/modgui.md']
TEMPLATE = [('templates/plugin/plugins/simple-echo/SimpleEchoPlugin.cpp', 'cpp'),
            ('templates/plugin/plugins/simple-echo/DistrhoPluginInfo.h', 'cpp'),
            ('templates/plugin/plugins/simple-echo/Makefile', 'makefile'),
            ('templates/plugin/bundle/simple-echo.lv2/manifest.ttl', 'turtle'),
            ('templates/plugin/bundle/simple-echo.lv2/simple-echo.ttl', 'turtle')]


COPIES = {'prompts/plugin-from-idea.md': 'plugin-from-idea.md', 'examples/gain.mk': 'gain.mk',
          'examples/ce2-chorus.mk': 'ce2-chorus.mk', 'LICENSE': 'LICENSE'}


def cookbook(path, rel):
    """Read a cookbook file from a checkout, from GitHub, or from our cookbook/ copy."""
    local = os.path.join(ROOT, 'cookbook', COPIES.get(rel, os.path.basename(rel)))
    try:
        if path:
            text = open(os.path.join(path, rel)).read()
        else:
            with urllib.request.urlopen(COOKBOOK_RAW + rel, timeout=20) as r:
                text = r.read().decode()
    except Exception:
        return open(local).read()
    os.makedirs(os.path.dirname(local), exist_ok=True)
    open(local, 'w').write(text)
    return text


def make_example():
    """Assemble the template (without its face images) into examples/simple-echo.mk."""
    tmp = tempfile.mkdtemp()
    try:
        b = os.path.join(tmp, 'simple-echo.lv2')
        shutil.copytree(os.path.join(ROOT, 'templates/plugin/bundle/simple-echo.lv2'), b)
        shutil.rmtree(os.path.join(b, 'modgui'), ignore_errors=True)
        if os.path.exists(os.path.join(b, 'modgui.ttl')):
            os.remove(os.path.join(b, 'modgui.ttl'))
        m = os.path.join(b, 'manifest.ttl')
        open(m, 'w').write(open(m).read().replace(' , <modgui.ttl>', ''))
        hdr = os.path.join(tmp, 'header.txt')
        open(hdr, 'w').write('Worked example from the MOD plugin playbook (MIT): the template echo as a\n'
                             'single-file recipe, with the playbook\'s rules applied (required features,\n'
                             'in-plugin bypass with Tails, wet-path limit, versioning). Copy its shape.\n'
                             'Generated by tools/make_all_in_one.py from templates/plugin; no pedal face.\n')
        out = os.path.join(ROOT, 'examples', 'simple-echo.mk')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        subprocess.run([sys.executable, os.path.join(ROOT, 'tools/assemble_recipe.py'),
                        os.path.join(ROOT, 'templates/plugin/plugins/simple-echo'), b, out, '--header', hdr],
                       check=True, stdout=subprocess.DEVNULL)
        return open(out).read()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def demote(md):
    """Push every heading down one level so each file sits under its own heading."""
    out, fence = [], False
    for line in md.splitlines():
        if line.startswith('```'):
            fence = not fence
        out.append('#' + line if (not fence and line.startswith('#')) else line)
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cookbook')
    a = ap.parse_args()
    rd = lambda p: open(os.path.join(ROOT, p)).read()
    try:
        rev = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'], text=True).strip()
    except Exception:
        rev = 'unknown'
    parts = ['''# MOD Plugin Playbook: all in one

Generated by `tools/make_all_in_one.py` on %s from playbook commit `%s`. Don't edit by hand.

**For the AI reading this:** this file stands in for the repo when you can't fetch it. It holds `AGENTS.md` (start there, and follow its kick-off), the MOD cookbook's recipe prompt with its worked example, the docs a single-`.mk` build needs, and a worked recipe (`examples/simple-echo.mk`). Where `AGENTS.md` says to fetch or read a file that is below, use the copy below. Files not included here (tests and tools) need a shell; say which checks you couldn't run.

**For the person:** attach this one file to a chat with any AI and say what plugin you'd like.

Licences: the playbook is MIT. The cookbook prompt is MIT, Copyright (c) 2026 MOD Audio Limited (notice at its end).
''' % (datetime.date.today().isoformat(), rev)]
    parts.append('# 1. AGENTS.md\n\n' + demote(rd('AGENTS.md')))
    cb = cookbook(a.cookbook, 'prompts/plugin-from-idea.md')
    lic = cookbook(a.cookbook, 'LICENSE')
    for rel in ('examples/gain.mk', 'examples/ce2-chorus.mk'):
        cookbook(a.cookbook, rel)
    example = make_example()
    parts.append('# 2. The MOD plugin cookbook: prompts/plugin-from-idea.md\n\nFrom github.com/mod-audio/mod-plugin-cookbook. Read it as the foundation; `AGENTS.md` lists where the playbook overrides it.\n\n'
                 + demote(cb) + '\n\n```text\n' + lic.strip() + '\n```')
    for i, p in enumerate(DOCS, 3):
        parts.append('# %d. %s\n\n%s' % (i, p, demote(rd(p))))
    n = 3 + len(DOCS)
    parts.append('# %d. examples/simple-echo.mk: the worked recipe (the template echo, parts tagged by trait)\n\n'
                 'The shape to copy for a single-file recipe, with the playbook\'s rules applied.\n\n```makefile\n%s\n```'
                 % (n, example.rstrip()))
    out = os.path.join(ROOT, 'ALL-IN-ONE.md')
    open(out, 'w').write('\n\n---\n\n'.join(parts) + '\n')
    print('wrote %s (%d KB)' % (out, os.path.getsize(out) // 1024))


if __name__ == '__main__':
    main()
